// Defined below; registry_global binds each wl_output with this listener.
static const struct wl_output_listener output_listener;

static void registry_global(void *data, struct wl_registry *reg, uint32_t name,
                            const char *interface, uint32_t version) {
    (void)data;
    if (strcmp(interface, wl_compositor_interface.name) == 0) {
        // v6 gives preferred_buffer_scale; bind low and read scale off
        // outputs instead, which every compositor supports.
        g.compositor = wl_registry_bind(reg, name, &wl_compositor_interface,
                                        version < 4 ? version : 4);
    } else if (strcmp(interface, wl_shm_interface.name) == 0) {
        g.shm = wl_registry_bind(reg, name, &wl_shm_interface, 1);
    } else if (strcmp(interface, xdg_wm_base_interface.name) == 0) {
        g.wm_base = wl_registry_bind(reg, name, &xdg_wm_base_interface, 1);
        xdg_wm_base_add_listener(g.wm_base, &wm_base_listener, NULL);
    } else if (strcmp(interface, wl_seat_interface.name) == 0) {
        // v8 gives axis_value120 (Windows-parity scrolling); v5 gives the
        // pointer.frame event scroll batching relies on.
        g.seat_version = version < 8 ? version : 8;
        g.seat = wl_registry_bind(reg, name, &wl_seat_interface, g.seat_version);
        wl_seat_add_listener(g.seat, &seat_listener, NULL);
    } else if (strcmp(interface, wl_output_interface.name) == 0) {
        // Bind each output (v2+ for the scale event) and track its integer
        // scale by index; wl_surface.enter then references one of these
        // objects, so it must be bound here for enter to fire at all.
        if (g.n_out < (int)(sizeof(g.out_objs) / sizeof(g.out_objs[0]))) {
            struct wl_output *o =
                wl_registry_bind(reg, name, &wl_output_interface, version < 2 ? version : 2);
            g.out_objs[g.n_out] = o;
            g.out_scales[g.n_out] = 1;
            wl_output_add_listener(o, &output_listener, (void *)(intptr_t)g.n_out);
            g.n_out++;
        }
    } else if (strcmp(interface, wl_data_device_manager_interface.name) == 0) {
        g.ddm = wl_registry_bind(reg, name, &wl_data_device_manager_interface,
                                 version < 3 ? version : 3);
    } else if (strcmp(interface, zwp_text_input_manager_v3_interface.name) == 0) {
        g.ti_manager =
            wl_registry_bind(reg, name, &zwp_text_input_manager_v3_interface, 1);
    }
}
