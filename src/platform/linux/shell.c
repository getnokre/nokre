    int sf_v120_x, sf_v120_y;
    wl_fixed_t sf_axis_x, sf_axis_y;

    // Integer output scales, tracked so wl_surface.enter can set g.scale.
    struct wl_output *out_objs[8];
    int32_t out_scales[8];
    int n_out;
    struct wl_output *surface_output; // the output the surface is on

    // The most recent input serial, for set_selection and IME commits.
    uint32_t last_serial;

    // text-input-v3 batch, applied on `done`.
    int ti_enabled;                 // enable sent, not yet disabled
    int ti_have_preedit;            // a preedit_string arrived this batch
    int ti_have_commit;             // a commit_string arrived this batch
    char ti_preedit[512];           // current composition
    int32_t ti_cursor;              // caret byte offset within ti_preedit
    char ti_commit[512];            // committed text this batch
    int ti_composing;               // a non-empty preedit is currently shown
    int ti_focused;                 // between text_input.enter and .leave
    uint32_t ti_serial;             // bump on every enable/commit, per protocol

    // Clipboard out: the current wl_data_source and the text it serves.
    struct wl_data_source *clip_source;
    char *clip_text;
    size_t clip_len;

