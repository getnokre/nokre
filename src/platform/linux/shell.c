// ---- the on-demand event loop ----

static void drain_posts(void) {
    for (;;) {
        pthread_mutex_lock(&g.post_lock);
        struct nokre_post_item *item = g.post_head;
        if (item != NULL) {
            g.post_head = item->next;
            if (g.post_head == NULL) g.post_tail = NULL;
        }
        pthread_mutex_unlock(&g.post_lock);
        if (item == NULL) break;
        item->work(item->ctx);
        free(item);
    }
}

