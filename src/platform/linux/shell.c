    int32_t repeat_rate;  // keys/sec, 0 disables
    int32_t repeat_delay; // ms before the first repeat
    uint32_t repeat_key;  // evdev keycode being repeated, 0 = none

    uint32_t seat_version; // bound wl_seat version (>= 8 gives value120)

    // Pointer: last surface-local position and the wheel remainder.
    int32_t ptr_x, ptr_y;
    int ptr_down; // a press is in flight, so motion is worth reporting
    int wheel_rem_x, wheel_rem_y; // value120 → px remainders
    int axis_rem_x, axis_rem_y;   // legacy wl_fixed axis → px remainders

    // Per-frame scroll accumulator (wl_pointer.frame batches axis events):
