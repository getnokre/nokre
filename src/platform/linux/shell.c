// ---- shm buffers ----

static int create_anon_fd(size_t size) {
    // memfd is Linux-native and needs no tmp path; libwayland is happy
    // with any fd that mmaps.
    int fd = memfd_create("nokre-shm", MFD_CLOEXEC);
    if (fd < 0) return -1;
    if (ftruncate(fd, (off_t)size) < 0) {
        close(fd);
        return -1;
    }
    return fd;
}

static void buffer_release(void *data, struct wl_buffer *wl_buffer) {
    (void)wl_buffer;
    int *busy = data;
    *busy = 0;
}
static const struct wl_buffer_listener buffer_listener = {.release = buffer_release};

// Ensures bufs[i] holds a wl_buffer sized w*h; returns 0 on failure.
static int ensure_buffer(int i, int32_t w, int32_t h) {
    if (g.bufs[i].buffer != NULL && g.bufs[i].w == w && g.bufs[i].h == h) return 1;
    if (g.bufs[i].buffer != NULL) {
        wl_buffer_destroy(g.bufs[i].buffer);
        munmap(g.bufs[i].data, g.bufs[i].cap);
        g.bufs[i].buffer = NULL;
    }
    size_t stride = (size_t)w * 4;
    size_t size = stride * (size_t)h;
    int fd = create_anon_fd(size);
    if (fd < 0) return 0;
    void *data = mmap(NULL, size, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
    if (data == MAP_FAILED) {
        close(fd);
        return 0;
    }
    struct wl_shm_pool *pool = wl_shm_create_pool(g.shm, fd, (int32_t)size);
    struct wl_buffer *buffer =
        wl_shm_pool_create_buffer(pool, 0, w, h, (int32_t)stride, WL_SHM_FORMAT_XRGB8888);
    wl_shm_pool_destroy(pool);
    close(fd);
    if (buffer == NULL) {
        munmap(data, size);
        return 0;
    }
    g.bufs[i].buffer = buffer;
    g.bufs[i].data = data;
    g.bufs[i].cap = size;
    g.bufs[i].w = w;
    g.bufs[i].h = h;
    g.bufs[i].busy = 0;
    wl_buffer_add_listener(buffer, &buffer_listener, &g.bufs[i].busy);
    return 1;
}

// Renders the current frame into a free buffer and commits it. Deferred
// (dirty stays set) when both buffers are still held by the compositor.
static void paint(void) {
    if (!g.configured || g.logical_w < 1 || g.logical_h < 1) return;
    int i = !g.bufs[0].busy ? 0 : (!g.bufs[1].busy ? 1 : -1);
    if (i < 0) {
        g.dirty = 1; // a release event will call back here
        return;
    }
    int32_t out_w = 0, out_h = 0;
    const uint8_t *pixels = g.config.on_frame(g.config.ctx, g.logical_w, g.logical_h, 0,
                                              g.scale, &out_w, &out_h);
    if (pixels == NULL || out_w <= 0 || out_h <= 0) return;
    if (!ensure_buffer(i, out_w, out_h)) return;

    // Expand gray8 to XRGB8888 (v | v<<8 | v<<16), one memcpy-shaped loop —
    // the Windows BGRX blit, byte-order-identical on little-endian.
    size_t count = (size_t)out_w * (size_t)out_h;
    uint32_t *dst = (uint32_t *)g.bufs[i].data;
    for (size_t p = 0; p < count; p++) {
        uint32_t v = pixels[p];
        dst[p] = v | (v << 8) | (v << 16);
    }

    g.bufs[i].busy = 1;
    g.dirty = 0;
    wl_surface_set_buffer_scale(g.surface, g.scale);
    wl_surface_attach(g.surface, g.bufs[i].buffer, 0, 0);
    // Damage everything (surface coords) — version-safe across wl_surface
    // v1+, unlike damage_buffer which is v4; the whole frame is fresh.
    wl_surface_damage(g.surface, 0, 0, INT32_MAX, INT32_MAX);
    wl_surface_commit(g.surface);
}

static void maybe_repaint(void) {
    if (g.config.wants_frame(g.config.ctx)) {
        g.dirty = 1;
        paint();
    }
}

