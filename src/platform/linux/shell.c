// Wayland shell. Thin by charter: a wl_surface, a gray8→XRGB blit into
// wl_shm buffers, input forwarding, text-input-v3 for IME. No timers past
// the one keyboard-repeat timerfd the compositor makes us own, no
// animation — nokre repaints only when state changes, and the event loop
// blocks in poll() at rest for zero idle CPU.
//
// X11 is deliberately not here (docs/roadmap.md): Wayland is the modern
// default and one backend is the charter. The pieces that ride this file
// without being part of the dumb shell contract — clipboard out, the
// deep-link inbound hook, the worker/a11y UI-thread hop — answer to their
// own service headers, exactly as the Windows and macOS shells arrange.
// _GNU_SOURCE (implies _POSIX_C_SOURCE): memfd_create, MFD_CLOEXEC, and
// the eventfd/SOCK_CLOEXEC flags are glibc extensions behind it.
