// Shows or hides the OS input path off wants_text_input, after each event —
// the iOS/web software-keyboard bargain: an on-screen keyboard (where the
// compositor offers one) follows the focused element's appetite for text.
static void sync_text_input(void) {
    // Only between enter and leave: the protocol forbids enable without
    // focus, and a disable is meaningless once the surface has lost it
    // (ti_leave already tore it down).
    if (g.text_input == NULL || !g.ti_focused) return;
    int want = g.config.wants_text_input(g.config.ctx) != 0;
    if (want && !g.ti_enabled) {
        zwp_text_input_v3_enable(g.text_input);
        // The document is only the composition (the other shells' rule):
        // no surrounding text, so the IME cannot be "smart".
        zwp_text_input_v3_set_content_type(
            g.text_input, ZWP_TEXT_INPUT_V3_CONTENT_HINT_NONE,
            ZWP_TEXT_INPUT_V3_CONTENT_PURPOSE_NORMAL);
        zwp_text_input_v3_commit(g.text_input);
        g.ti_enabled = 1;
        g.ti_serial++;
    } else if (!want && g.ti_enabled) {
        zwp_text_input_v3_disable(g.text_input);
        zwp_text_input_v3_commit(g.text_input);
        g.ti_enabled = 0;
        g.ti_serial++;
        if (g.ti_composing) {
            g.config.on_ime_cancel(g.config.ctx);
            g.ti_composing = 0;
        }
    }
}

